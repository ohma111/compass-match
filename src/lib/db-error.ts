// DBエラーを利用者向けの日本語メッセージへ変換する。
// RPC内で raise した例外はすでに日本語なのでそのまま返す。
// それ以外(制約違反など)は詳細を出さず一般的な文言にする (内部情報を漏らさない)。
export interface PgLikeError {
  code?: string;
  message?: string;
}

const JAPANESE = /[぀-ヿ一-龯]/;

// 古いマイグレーションで定義した、くだけた言い回しの例外文を言い換える
const REWORD: Record<string, string> = {
  '送りすぎです。1分ほど待ってください': '送信が多すぎます。1分ほど待ってからお試しください',
  '連続で送れません。少し待ってください': '続けて送信することはできません。少し待ってから送信してください',
  '同じ文は続けて送れません': '同じ内容は続けて送信できません',
  '使えない言葉が入っています': '使用できない言葉が含まれています',
  'ゲームへの姿勢を選んでください': '遊び方を選んでください',
  'ランク帯を選んでください': 'ランクを選んでください',
  'はじめて10分は10件までです。ちょっと待ってから送ってください': '登録から10分間は10件まで送信できます。少し待ってから送信してください',
  '先に登録を完了してください': '先にプロフィールを作成してください',
  'この人の通知は受け取れません': 'この方の通知は受け取れません',
  '不正なリクエストです': '操作できませんでした。ページを再読み込みしてください',
  '不正な操作です': '操作できませんでした。ページを再読み込みしてください',
  '通報対象が不正です': '通報できませんでした。ページを再読み込みしてください',
  '参加方式が不正です': '参加方式を選び直してください',
  '満員です': '満員のため参加できません',
};

export function toUserMessage(err: PgLikeError | null | undefined): string {
  if (!err) return 'エラーが発生しました。もう一度お試しください';
  const code = err.code ?? '';
  const msg = err.message ?? '';
  if (['P0001', 'P0002', 'P0429', '22023', '28000', '42501'].includes(code) && JAPANESE.test(msg)) return REWORD[msg] ?? msg;
  if (code === '23514') return '使用できない文字や言葉が含まれています';
  if (code === '23505') return 'すでに登録されています';
  if (code === '42501') return 'この操作を行う権限がありません';
  if (code === 'PGRST301' || code === '28000') return 'ログインが必要です';
  return 'エラーが発生しました。もう一度お試しください';
}
